// Exports the looks (Graphite, the default, then Warm and Ghostty; dark and light) from the native app's tokens to the web
// client: chrome colours from src/theme.odin, terminal colours from src/core/term_palette.odin.
// Writes web/src/theme.gen.css (CSS variables) and web/src/theme.gen.ts (xterm.js colours).
// Run by build.mjs; the outputs are committed so typecheck and tests need no build.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(web, "..");

// The `.<Look> = { … }` block of the table that starts with `table :=`.
function block(src, table, look = "Graphite") {
  const at = src.indexOf(table + " :=");
  if (at < 0) throw new Error(`no ${table} in the Odin source`);
  const g = src.indexOf("." + look + " =", at);
  if (g < 0) throw new Error(`no ${look} in ${table}`);
  const open = src.indexOf("{", g);
  let depth = 0;
  for (let i = open; i < src.length; i++) {
    if (src[i] === "{") depth++;
    else if (src[i] === "}" && --depth === 0) return src.slice(open + 1, i);
  }
  throw new Error(`unclosed ${look} block in ${table}`);
}

function hex(nums) {
  const [r, g, b, a = 255] = nums.map((n) => Number(n));
  const h = (x) => x.toString(16).padStart(2, "0");
  return a === 255 ? `#${h(r)}${h(g)}${h(b)}` : `rgba(${r}, ${g}, ${b}, ${(a / 255).toFixed(3)})`;
}

function rgba(s) {
  return hex(s.split(",").map((x) => x.trim()).filter(Boolean));
}

function chrome(body) {
  const out = {};
  for (const m of body.matchAll(/(\w+)\s*=\s*\{([^}]*)\}/g)) out[m[1]] = rgba(m[2]);
  return out;
}

function term(body) {
  const one = (name) => rgba(body.match(new RegExp(`${name}\\s*=\\s*\\{([^}]*)\\}`))[1]);
  const ansiBody = body.slice(body.indexOf("ansi"));
  const ansi = [...ansiBody.matchAll(/\{(0x[^}]*)\}/g)].map((m) => rgba(m[1]));
  if (ansi.length !== 16) throw new Error("expected 16 ANSI colours");
  return { fg: one("fg"), bg: one("bg"), cursor: one("cursor"), ansi };
}

const theme = readFileSync(join(repo, "src/theme.odin"), "utf8");
const palette = readFileSync(join(repo, "src/core/term_palette.odin"), "utf8");
const LOOKS = ["Graphite", "Warm", "Ghostty"];
const looks = {};
for (const L of LOOKS) {
  const dark = chrome(block(theme, "THEMES", L));
  const light = chrome(block(theme, "THEMES_LIGHT", L));
  looks[L.toLowerCase()] = {
    dark,
    light,
    term: {
      dark: { ...term(block(palette, "TERM_COLORS", L)), selection: dark.term_selection },
      light: { ...term(block(palette, "TERM_COLORS_LIGHT", L)), selection: light.term_selection },
    },
  };
}
const { dark, light } = looks.graphite;

const KEYS = ["bg_app", "bg_sidebar", "bg_panel", "bg_elevated", "bg_field", "hover", "selected", "text", "text_secondary", "text_muted", "text_on_accent", "border", "accent", "selection", "scrim", "shadow", "running", "waiting", "done", "error"];
const vars = (t) => KEYS.map((k) => `  --${k.replace(/_/g, "-")}: ${t[k]};`).join("\n");

// the other looks: the page sets data-look and data-light on <html> (app/App.tsx)
const others = LOOKS.slice(1)
  .map((L) => {
    const k = L.toLowerCase();
    return `:root[data-look="${k}"]:not([data-light="1"]) {\n  color-scheme: dark;\n${vars(looks[k].dark)}\n}\n:root[data-look="${k}"][data-light="1"] {\n  color-scheme: light;\n${vars(looks[k].light)}\n}\n`;
  })
  .join("");

const css = `/* Generated by web/tools/theme.mjs from src/theme.odin (every look). Do not edit. */
:root {
  color-scheme: dark;
${vars(dark)}
}
@media (prefers-color-scheme: light) {
  :root:not([data-appearance="dark"]) {
    color-scheme: light;
${vars(light).replace(/^/gm, "  ")}
  }
}
:root[data-appearance="light"] {
  color-scheme: light;
${vars(light)}
}
${others}`;

const termLooks = Object.fromEntries(Object.entries(looks).map(([k, v]) => [k, v.term]));
const ts = `// Generated by web/tools/theme.mjs from src/core/term_palette.odin (every look). Do not edit.
export interface TermColors {
  fg: string;
  bg: string;
  cursor: string;
  selection: string;
  ansi: string[];
}
export const TERM_LOOKS: Record<string, { dark: TermColors; light: TermColors }> = ${JSON.stringify(termLooks)};
`;

writeFileSync(join(web, "src/theme.gen.css"), css);
writeFileSync(join(web, "src/theme.gen.ts"), ts);
